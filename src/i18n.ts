export type TranslationKey = keyof typeof en;
export const resources = { en, nl };
export function translate(language: "en" | "nl", key: string) {
  const selected = resources[language] as Record<string, string>;
  const fallback = en as Record<string, string>;
  if (!selected[key] && !fallback[key] && import.meta.env.DEV)
    console.warn(`Missing translation key: ${key}`);
  return selected[key] || fallback[key] || key;
}
export function useT() {
  const { language } = useApp();
  return (key: string) => translate(language, key);
}
export function missingTranslationKeys() {
  return Object.keys(en).filter((key) => !nl[key as keyof typeof en]);
}
